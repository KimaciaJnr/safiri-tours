export const allPackages = [
  ...nairobiSafariPackages,
  ...coastalSafariPackages.filter(
    (p) => !nairobiSafariPackages.some((n) => n.slug === p.slug)
  ),
  ...flyInPackages,
  ...beachPackages,
  ...budgetMaraPackages.filter(
    (p) => !nairobiSafariPackages.some((n) => n.slug === p.slug) && !coastalSafariPackages.some((c) => c.slug === p.slug)
  ),
];

export function getPackageBySlug(slug) {
  return allPackages.find((p) => p.slug === slug) || null;
}

export function getPackagesByCategory(category) {
  return allPackages.filter((p) => p.category === category);
}

export function getRelatedPackages(pkg, count = 3) {
  return allPackages
    .filter((p) => p.category === pkg.category && p.slug !== pkg.slug)
    .slice(0, count);
}
